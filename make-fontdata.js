// make-fontdata.js
// Run after changing the files in /fonts:  node make-fontdata.js
// It writes js/fontdata.js: the fonts as base64 text, so every downloaded site
// carries its own fonts inside its one HTML file and still works offline.

const fs = require("fs");

const files = ["fraunces-400", "fraunces-700", "dm-sans-400", "dm-sans-700", "jetbrains-mono-400"];

const lines = files.map(name => {
  const base64 = fs.readFileSync("fonts/" + name + ".woff2").toString("base64");
  return '  "' + name + '": "' + base64 + '"';
});

const output = "// Generated by make-fontdata.js from the files in /fonts. Do not edit by hand.\n" +
  "// Base64 copies of the fonts, so a downloaded site carries its own fonts and works offline.\n" +
  "const FONT_DATA = {\n" + lines.join(",\n") + "\n};\n";

fs.writeFileSync("js/fontdata.js", output);
console.log("Wrote js/fontdata.js (" + Math.round(output.length / 1024) + " KB)");
